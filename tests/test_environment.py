def test_adopt_skips_generated_marker_files(tmp_path: Path) -> None:
    repo = init_repo(tmp_path / "repo")
    home = tmp_path / "home"
    home.mkdir()
    claude = repo / "CLAUDE.md"
    generated = "<!-- AUTO-GENERATED by ruler. DO NOT EDIT. -->\n\n# Rules\n\nGenerated content.\n"
    claude.write_text(generated, encoding="utf-8")

    payload = adopt(repo, home)

    claude_entry = next(item for item in payload["integrations"] if item["name"] == "claude")
    assert claude_entry["skipped"] and "generated" in claude_entry["skipped"]
    assert claude.read_text(encoding="utf-8") == generated
    agents_text = (repo / "AGENTS.md").read_text(encoding="utf-8")
    assert "agentdir-managed-generic:start" in agents_text

    doctor = json.loads(
        run_cli("integrations", "doctor", "--json", cwd=repo, env_extra={"HOME": str(home)}).stdout
    )
    claude_check = next(check for check in doctor["checks"] if check["name"] == "claude")
    assert claude_check["state"] == "generated"
    assert doctor["ok"] is True


