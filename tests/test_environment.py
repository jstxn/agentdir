def test_hooks_install_in_linked_worktree_targets_shared_hooks_dir(tmp_path: Path) -> None:
    repo = init_repo(tmp_path / "repo")
    (repo / "README.md").write_text("hello\n", encoding="utf-8")
    subprocess.run(["git", "add", "README.md"], cwd=repo, check=True)
    subprocess.run(
        ["git", "commit", "-m", "init"],
        cwd=repo,
        check=True,
        text=True,
        capture_output=True,
    )
    worktree = tmp_path / "wt"
    subprocess.run(
        ["git", "worktree", "add", str(worktree)],
        cwd=repo,
        check=True,
        text=True,
        capture_output=True,
    )

    run_cli("hooks", "install", "--hook", "pre-commit", cwd=worktree)

    shared_hook = repo / ".git" / "hooks" / "pre-commit"
    assert shared_hook.is_file()
    assert "AgentDir managed hook" in shared_hook.read_text(encoding="utf-8")
    assert not (repo / ".git" / "worktrees" / worktree.name / "hooks" / "pre-commit").exists()


def test_adopt_dry_run_reports_hook_managers(tmp_path: Path) -> None:
    repo = init_repo(tmp_path / "repo")
    home = tmp_path / "home"
    home.mkdir()
    (repo / "lefthook.yml").write_text("pre-commit:\n  jobs:\n    - run: echo lint\n", encoding="utf-8")
    (repo / ".husky").mkdir()
    (repo / ".pre-commit-config.yaml").write_text("repos: []\n", encoding="utf-8")
    (repo / "package.json").write_text(
        json.dumps({"devDependencies": {"lefthook": "^1.0.0"}}), encoding="utf-8"
    )

    plan = json.loads(
        run_cli(
            "adopt",
            "--dry-run",
            "--gitignore",
            "none",
            "--json",
            cwd=repo,
            env_extra={"HOME": str(home)},
        ).stdout
    )

    managers = {manager["name"] for manager in plan["environment"]["hook_managers"]}
    assert {"lefthook", "husky", "pre-commit"} <= managers
    lefthook = next(m for m in plan["environment"]["hook_managers"] if m["name"] == "lefthook")
    assert str(repo / "lefthook.yml") in lefthook["evidence"]
    assert str(repo / "package.json") in lefthook["evidence"]
    assert any("lefthook" in warning for warning in plan["warnings"])
    assert not (repo / ".agentdir").exists()
