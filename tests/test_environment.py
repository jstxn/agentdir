def test_hooks_manifest_written_and_doctor_flags_clobbered_hook(tmp_path: Path) -> None:
    repo = init_repo(tmp_path / "repo")
    run_cli("hooks", "install", "--hook", "pre-commit", cwd=repo)

    manifest = json.loads((repo / ".agentdir" / "hooks.json").read_text(encoding="utf-8"))
    assert manifest["hooks"] == ["pre-commit"]
    assert manifest["repo"] == str(repo.resolve())

    clean = json.loads(run_cli("doctor", "--json", cwd=repo).stdout)
    assert not any("pre-commit" in warning for warning in clean["warnings"])

    hook = repo / ".git" / "hooks" / "pre-commit"
    hook.write_text(LEFTHOOK_SCRIPT.format(hook="pre-commit"), encoding="utf-8")
    report = json.loads(run_cli("doctor", "--json", cwd=repo).stdout)

    assert report["ok"] is True
    assert any(
        "pre-commit" in warning and "overwritten by lefthook" in warning
        for warning in report["warnings"]
    )

    hook.unlink()
    report = json.loads(run_cli("doctor", "--json", cwd=repo).stdout)
    assert any("missing" in warning and "pre-commit" in warning for warning in report["warnings"])


def test_hooks_install_self_heals_after_hook_manager_reinstall(tmp_path: Path) -> None:
    repo = init_repo(tmp_path / "repo")
    hook = repo / ".git" / "hooks" / "pre-commit"
    hook.write_text(LEFTHOOK_SCRIPT.format(hook="pre-commit") + "# v1\n", encoding="utf-8")
    hook.chmod(0o755)

    run_cli("hooks", "install", "--hook", "pre-commit", cwd=repo)
    original = repo / ".git" / "hooks" / "pre-commit.agentdir-original"
    assert "# v1" in original.read_text(encoding="utf-8")

    # Simulate `lefthook install` clobbering the shim with a fresh script.
    hook.write_text(LEFTHOOK_SCRIPT.format(hook="pre-commit") + "# v2\n", encoding="utf-8")
    result = run_cli("hooks", "install", "--hook", "pre-commit", cwd=repo)

    assert "chains lefthook" in result.stdout
    assert "AgentDir managed hook" in hook.read_text(encoding="utf-8")
    assert "# v2" in original.read_text(encoding="utf-8")

    status = json.loads(run_cli("hooks", "status", "--hook", "pre-commit", "--json", cwd=repo).stdout)
    assert status[0]["managed"] is True


def test_hooks_install_still_refuses_when_backup_is_custom(tmp_path: Path) -> None:
    repo = init_repo(tmp_path / "repo")
    hook = repo / ".git" / "hooks" / "pre-commit"
    hook.write_text("#!/bin/sh\necho custom-hook\n", encoding="utf-8")
    hook.chmod(0o755)

    run_cli("hooks", "install", "--hook", "pre-commit", cwd=repo)
    hook.write_text(LEFTHOOK_SCRIPT.format(hook="pre-commit"), encoding="utf-8")

    refused = run_cli("hooks", "install", "--hook", "pre-commit", cwd=repo, expected_returncode=2)
    assert "Refusing to overwrite" in refused.stderr
    original = repo / ".git" / "hooks" / "pre-commit.agentdir-original"
    assert "custom-hook" in original.read_text(encoding="utf-8")


