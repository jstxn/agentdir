from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path


def find_project_root() -> Path:
    for candidate in Path(__file__).resolve().parents:
        if (candidate / "pyproject.toml").is_file():
            return candidate
    raise RuntimeError("could not locate project root")


PROJECT_ROOT = find_project_root()
SRC_ROOT = PROJECT_ROOT / "src"

LEFTHOOK_SCRIPT = '#!/bin/sh\n# lefthook\ncall_lefthook run "{hook}" "$@"\n'


def run_cli(
    *args: str,
    cwd: Path | None = None,
    env_extra: dict[str, str] | None = None,
    expected_returncode: int = 0,
) -> subprocess.CompletedProcess[str]:
    env = os.environ.copy()
    env["PYTHONPATH"] = str(SRC_ROOT)
    if env_extra:
        env.update(env_extra)
    result = subprocess.run(
        [sys.executable, "-m", "agentdir", *args],
        cwd=cwd or PROJECT_ROOT,
        env=env,
        text=True,
        capture_output=True,
    )
    assert result.returncode == expected_returncode, (
        f"expected exit code {expected_returncode}, got {result.returncode}\n"
        f"stdout:\n{result.stdout}\n"
        f"stderr:\n{result.stderr}"
    )
    return result


def init_repo(path: Path) -> Path:
    path.mkdir()
    subprocess.run(["git", "init"], cwd=path, check=True, text=True, capture_output=True)
    subprocess.run(["git", "config", "user.email", "agentdir@example.test"], cwd=path, check=True)
    subprocess.run(["git", "config", "user.name", "AgentDir Test"], cwd=path, check=True)
    return path


def adopt(repo: Path, home: Path, *extra: str) -> dict[str, object]:
    result = run_cli(
        "adopt",
        "--install-skill",
        "none",
        "--gitignore",
        "none",
        "--no-hooks",
        *extra,
        "--json",
        cwd=repo,
        env_extra={"HOME": str(home)},
    )
    return json.loads(result.stdout)


def test_adopt_redirects_integrations_to_rulesync_source_rule(tmp_path: Path) -> None:
    repo = init_repo(tmp_path / "repo")
    home = tmp_path / "home"
    home.mkdir()
    (repo / ".rulesync" / "rules").mkdir(parents=True)

    payload = adopt(repo, home)
    rule = repo / ".rulesync" / "rules" / "agentdir.md"

    assert [generator["name"] for generator in payload["environment"]["rule_generators"]] == ["rulesync"]
    assert [item["name"] for item in payload["integrations"]] == ["rulesync"]
    assert any("rulesync" in warning for warning in payload["warnings"])
    skipped = {adjustment["name"] for adjustment in payload["adjustments"]}
    assert {"generic", "claude", "copilot", "cursor", "windsurf"} == skipped
    assert rule.is_file()
    rule_text = rule.read_text(encoding="utf-8")
    assert rule_text.startswith("---\nroot: false\n")
    assert 'targets: ["*"]' in rule_text
    assert "<!-- agentdir-managed-rulesync:start -->" in rule_text
    assert "agentdir work start" in rule_text
    assert not (repo / "CLAUDE.md").exists()
    assert not (repo / "AGENTS.md").exists()
    assert not (repo / ".cursor").exists()
    assert not (repo / ".windsurf").exists()
    assert not (repo / ".github").exists()


